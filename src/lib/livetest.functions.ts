import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";
import { liveGate, type LiveEvidence, type LiveVerdict } from "@/lib/realitygate";

const Input = z.object({ url: z.string().url().max(2000), prompt: z.string().min(3).max(2000) });

type Action =
  | { type: "wait"; milliseconds: number }
  | { type: "click"; selector: string }
  | { type: "write"; text: string }
  | { type: "press"; key: string }
  | { type: "scroll"; direction: "up" | "down" }
  | { type: "screenshot" };

export type Plan = { steps: string[]; actions: Action[]; expectedTexts: string[]; forbiddenTexts: string[] };

export type LiveReport = {
  id: string;
  url: string;
  prompt: string;
  createdAt: string;
  verdict: LiveVerdict;
  confidence: number;
  plan: Plan;
  evidence: LiveEvidence[];
  screenshots: string[];
  pageTitle: string;
  found: string[];
  missing: string[];
  narrative: string;
  nextSteps: string[];
  playwright: string;
  errors: string[];
};

async function ai(prompt: string): Promise<string> {
  const { createOpenAI } = await import("@ai-sdk/openai");
  const { generateText } = await import("ai");
  const apiKey = process.env["LOVABLE_API_KEY"]!;
  const provider = createOpenAI({
    baseURL: "https://ai.gateway.lovable.dev/v1",
    apiKey,
    headers: { "Lovable-API-Key": apiKey, "X-Lovable-AIG-SDK": "vercel-ai-sdk" },
  });
  const r = await generateText({
    model: provider.responses("openai/gpt-6-astra"),
    prompt,
    providerOptions: { openai: { reasoningEffort: "low", store: false } },
  });
  return r.text;
}
const parseJson = (t: string) => JSON.parse(t.slice(t.indexOf("{"), t.lastIndexOf("}") + 1));

async function firecrawl(url: string, actions: Action[]) {
  const lov = process.env["LOVABLE_API_KEY"];
  const fc = process.env["FIRECRAWL_API_KEY"];
  if (!lov || !fc) throw new Error("Website reader (Firecrawl) is not connected");
  const res = await fetch("https://connector-gateway.lovable.dev/firecrawl/v2/scrape", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${lov}`, "X-Connection-Api-Key": fc },
    body: JSON.stringify({
      url,
      formats: ["markdown", { type: "screenshot", fullPage: false }],
      onlyMainContent: false,
      waitFor: 1500,
      timeout: 90000,
      ...(actions.length ? { actions } : {}),
    }),
  });
  const body = await res.text();
  if (!res.ok) throw new Error(`Scrape failed [${res.status}]: ${body.slice(0, 300)}`);
  const j = JSON.parse(body);
  const d = j.data ?? j;
  return {
    markdown: String(d.markdown ?? ""),
    screenshot: d.screenshot as string | undefined,
    actionShots: (d.actions?.screenshots ?? []) as string[],
    statusCode: (d.metadata?.statusCode ?? null) as number | null,
    title: String(d.metadata?.title ?? ""),
  };
}

function recipe(url: string, plan: Plan) {
  const lines = plan.actions.map((a) => {
    if (a.type === "click") return `  await page.locator(${JSON.stringify(a.selector)}).first().click();`;
    if (a.type === "write") return `  await page.keyboard.type(${JSON.stringify(a.text)});`;
    if (a.type === "press") return `  await page.keyboard.press(${JSON.stringify(a.key)});`;
    if (a.type === "wait") return `  await page.waitForTimeout(${a.milliseconds});`;
    if (a.type === "scroll") return `  await page.mouse.wheel(0, ${a.direction === "down" ? 800 : -800});`;
    return `  await page.screenshot({ path: "step.png" });`;
  });
  const exp = plan.expectedTexts.map((t) => `  await expect(page.getByText(${JSON.stringify(t)}).first()).toBeVisible();`);
  const forb = plan.forbiddenTexts.map((t) => `  await expect(page.getByText(${JSON.stringify(t)})).toHaveCount(0);`);
  return `import { test, expect } from "@playwright/test";

// Guardrail generated by RealityGate
test(${JSON.stringify(plan.steps[0] ?? "user flow works")}, async ({ page }) => {
  const res = await page.goto(${JSON.stringify(url)});
  expect(res?.status()).toBeLessThan(400);
${[...lines, ...exp, ...forb].join("\n")}
});`;
}

const ALLOWED = new Set(["wait", "click", "write", "press", "scroll", "screenshot"]);

export const runLiveTest = createServerFn({ method: "POST" })
  .validator((d: unknown) => Input.parse(d))
  .handler(async ({ data }): Promise<LiveReport> => {
    const errors: string[] = [];
    const evidence: LiveEvidence[] = [];
    let n = 0;
    const push = (e: Omit<LiveEvidence, "id">) => evidence.push({ id: `E${++n}`, ...e });

    // 1) Plan with AI (look at the page first so selectors are realistic)
    let preview = "";
    try {
      preview = (await firecrawl(data.url, [])).markdown.slice(0, 6000);
    } catch (e) {
      errors.push(e instanceof Error ? e.message : String(e));
    }
    let plan: Plan = { steps: ["Open the page"], actions: [], expectedTexts: [], forbiddenTexts: ["Something went wrong", "Internal Server Error", "404"] };
    try {
      const j = parseJson(
        await ai(`You plan browser tests. Reply ONLY JSON:
{"steps": string[] (plain-English test steps),
 "actions": array of Firecrawl actions, max 8, using only {"type":"click","selector":CSS} | {"type":"write","text"} | {"type":"press","key"} | {"type":"wait","milliseconds"} | {"type":"scroll","direction":"down"} | {"type":"screenshot"}. Click an input before "write". Use selectors likely present in the page. Include a "screenshot" after key steps. Empty array if the test only needs to look at the page.
 "expectedTexts": string[] (1-5 short exact texts that MUST be visible if the user's expectation holds),
 "forbiddenTexts": string[] (texts that indicate failure, e.g. error messages)}
URL: ${data.url}
User test: ${data.prompt}
Current page content:
${preview}`),
      );
      plan = {
        steps: Array.isArray(j.steps) ? j.steps.map(String).slice(0, 10) : plan.steps,
        actions: Array.isArray(j.actions) ? j.actions.filter((a: Action) => a && ALLOWED.has(a.type)).slice(0, 8) : [],
        expectedTexts: Array.isArray(j.expectedTexts) ? j.expectedTexts.map(String).filter(Boolean).slice(0, 5) : [],
        forbiddenTexts: Array.isArray(j.forbiddenTexts) ? j.forbiddenTexts.map(String).filter(Boolean).slice(0, 5) : plan.forbiddenTexts,
      };
    } catch (e) {
      errors.push(`AI planning failed: ${e instanceof Error ? e.message : String(e)}`);
    }

    // 2) Execute in a real browser via Firecrawl
    push({ kind: "action", label: `Navigate to ${data.url}`, detail: `Planned ${plan.actions.length} browser actions`, ok: true });
    let result: Awaited<ReturnType<typeof firecrawl>> | null = null;
    let actionsError: string | undefined;
    let scrapeError: string | undefined;
    try {
      result = await firecrawl(data.url, plan.actions);
      for (const a of plan.actions) push({ kind: "action", label: `${a.type} ${"selector" in a ? a.selector : "text" in a ? `"${a.text}"` : "key" in a ? a.key : ""}`.trim(), detail: "executed", ok: true });
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      if (plan.actions.length) {
        actionsError = msg;
        push({ kind: "action", label: "Browser actions failed", detail: msg, ok: false });
        try { result = await firecrawl(data.url, []); } catch (e2) { scrapeError = e2 instanceof Error ? e2.message : String(e2); }
      } else scrapeError = msg;
    }
    if (scrapeError) push({ kind: "network", label: "Page could not be loaded", detail: scrapeError, ok: false });
    if (result) push({ kind: "network", label: `GET ${data.url} → ${result.statusCode ?? "?"}`, detail: result.title || "(no title)", ok: (result.statusCode ?? 0) < 400 });

    const gate = liveGate({
      statusCode: result?.statusCode ?? null,
      scrapeError, actionsError,
      pageText: result?.markdown ?? "",
      expectedTexts: plan.expectedTexts,
      forbiddenTexts: plan.forbiddenTexts,
    });
    for (const t of gate.found) push({ kind: "dom", label: `Found “${t}”`, detail: "text present on page", ok: true });
    for (const t of gate.missing) push({ kind: "dom", label: `Missing “${t}”`, detail: "not present on page", ok: false });
    for (const t of gate.errorsSeen) push({ kind: "dom", label: `Error text “${t}” visible`, detail: "failure indicator on page", ok: false });
    const screenshots = [...(result?.actionShots ?? []), ...(result?.screenshot ? [result.screenshot] : [])];
    screenshots.forEach((s, i) => push({ kind: "screenshot", label: `Screenshot ${i + 1}`, detail: s, ok: true, screenshot: s }));

    // 3) AI narrative (cannot change the verdict)
    let narrative = "";
    let nextSteps: string[] = [];
    try {
      const j = parseJson(
        await ai(`You are RealityGate's reporter. Reply ONLY JSON {"narrative": string (3-5 sentences, cite evidence ids like [E2], never claim anything not in evidence), "nextSteps": string[] (3 actions)}.
User test: ${data.prompt}
Verdict (authoritative, do not contradict): ${gate.verdict}
Evidence:
${evidence.map((e) => `[${e.id}] ${e.label} — ${e.detail.slice(0, 200)}`).join("\n")}
Page excerpt:
${(result?.markdown ?? "").slice(0, 3000)}`),
      );
      narrative = String(j.narrative ?? "");
      nextSteps = Array.isArray(j.nextSteps) ? j.nextSteps.map(String).slice(0, 5) : [];
    } catch (e) {
      errors.push(`AI report failed: ${e instanceof Error ? e.message : String(e)}`);
    }

    return {
      id: crypto.randomUUID(),
      url: data.url, prompt: data.prompt, createdAt: new Date().toISOString(),
      verdict: gate.verdict, confidence: gate.confidence, plan, evidence, screenshots,
      pageTitle: result?.title ?? "", found: gate.found, missing: gate.missing,
      narrative, nextSteps, playwright: recipe(data.url, plan), errors,
    };
  });
